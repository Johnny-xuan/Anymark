const listeners = new Set();

function detectDefaultLang() {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (saved && MESSAGES[saved]) return saved;
  } catch {}
  const nav = (typeof navigator !== 'undefined' && navigator.language) || 'zh-CN';
  if (nav.startsWith('ja')) return 'ja';
  if (nav === 'zh-TW' || nav === 'zh-HK' || nav.startsWith('zh-Hant')) return 'zh-TW';
  if (nav.startsWith('en')) return 'en';
  return 'zh-CN';
}

let currentLang = detectDefaultLang();

export function getLang() {
  return currentLang;
}

export function setLang(lang) {
  if (!MESSAGES[lang]) return;
  currentLang = lang;
  try { localStorage.setItem(LANG_KEY, lang); } catch {}
  try { globalThis.chrome?.storage?.local?.set({ [LANG_KEY]: lang }); } catch {}
  document.documentElement.lang = lang;
  applyI18n();
  for (const fn of listeners) fn(lang);
}

export function onLangChange(fn) {
  listeners.add(fn);
  return () => listeners.delete(fn);
}

export function t(key, vars = {}) {
  const table = MESSAGES[currentLang] || MESSAGES['zh-CN'];
  let str = table[key] ?? MESSAGES['zh-CN'][key] ?? key;
  for (const [k, v] of Object.entries(vars)) {
    str = str.replaceAll(`{${k}}`, String(v));
  }
  return str;
}

export function applyI18n(root = document) {
  document.documentElement.lang = currentLang;
  for (const el of root.querySelectorAll('[data-i18n]')) {
    el.textContent = t(el.dataset.i18n);
  }
  for (const el of root.querySelectorAll('[data-i18n-placeholder]')) {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  }
  for (const el of root.querySelectorAll('[data-i18n-title]')) {
    const val = t(el.dataset.i18nTitle);
    el.title = val;
    el.setAttribute('aria-label', val);
  }
  for (const el of root.querySelectorAll('[data-i18n-aria]')) {
    el.setAttribute('aria-label', t(el.dataset.i18nAria));
  }
}

if (typeof window !== 'undefined') {
  window.addEventListener('storage', event => {
    if (event.key === LANG_KEY && event.newValue && MESSAGES[event.newValue] && event.newValue !== currentLang) {
      currentLang = event.newValue;
      applyI18n();
      for (const fn of listeners) fn(currentLang);
    }
  });
  try {
    globalThis.chrome?.storage?.local?.get([LANG_KEY], res => {
      const saved = res?.[LANG_KEY];
      if (saved && MESSAGES[saved] && saved !== currentLang) {
        currentLang = saved;
        try { localStorage.setItem(LANG_KEY, saved); } catch {}
        applyI18n();
        for (const fn of listeners) fn(currentLang);
      }
    });
    globalThis.chrome?.storage?.onChanged?.addListener((changes, area) => {
      const next = area === 'local' && changes[LANG_KEY]?.newValue;
      if (next && MESSAGES[next] && next !== currentLang) {
        currentLang = next;
        try { localStorage.setItem(LANG_KEY, next); } catch {}
        applyI18n();
        for (const fn of listeners) fn(currentLang);
      }
    });
  } catch {}
}
